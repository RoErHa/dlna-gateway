#!/usr/bin/env python3
"""
tools/versions.py — the "what is this actually built from" strip in README.md.

A version a reader cannot trust is worse than none, so every badge here is
READ from the thing it describes, never typed:

  RUNTIME   python · sqlite · openssl   the .venv interpreter (sqlite and
                                        openssl are what IT loads — Homebrew
                                        libraries, not part of Python)
            fastapi · starlette · …     requirements.lock
            hls.js                      the vendored static/vendor/hls.min.js
  TOOLING   node                        the Node that Playwright BUNDLES —
                                        the app itself never runs Node
            playwright · ruff           requirements-dev.lock
            ffmpeg                      the binary on PATH (optional: video)
  SECURITY  known vulnerabilities       osv.dev, on --write only (network)

Two kinds of truth, checked in two places. PINNED versions (the locks,
hls.js) are the same on every clone, so `tests/test_versions.py` gates
them like the test counts. PLATFORM versions (python, sqlite, openssl,
node, ffmpeg) belong to THIS machine and move with every `brew upgrade`;
gating them in the suite would turn every clone with another Python red.
`tools/upgrade.py` owns those: `--check` reports a stale strip as a DO
item, and a passing `--apply` rewrites it.

    .venv/bin/python tools/versions.py            # show; exit 1 if stale
    .venv/bin/python tools/versions.py --write    # rewrite (queries osv.dev)
"""
from __future__ import annotations

import datetime
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
README = PROJECT / "README.md"
VENV_PY = PROJECT / ".venv" / "bin" / "python"
LOCK = PROJECT / "requirements.lock"
DEV_LOCK = PROJECT / "requirements-dev.lock"
HLS = PROJECT / "static" / "vendor" / "hls.min.js"

BEGIN = "<!-- versions: generated by tools/versions.py -->"
END = "<!-- /versions -->"
SHIELDS = "https://img.shields.io/badge"

# (label, lock, package) — the runtime packages worth a reader's attention:
# the server edge, the two that parse untrusted media, the file watcher.
RUNTIME_PKGS = [("fastapi", LOCK, "fastapi"), ("starlette", LOCK, "starlette"),
                ("hypercorn", LOCK, "hypercorn"), ("pillow", LOCK, "pillow"),
                ("mutagen", LOCK, "mutagen"), ("watchdog", LOCK, "watchdog")]
TOOLING_PKGS = [("playwright", DEV_LOCK, "playwright"), ("ruff", DEV_LOCK, "ruff")]


# ── pure ─────────────────────────────────────────────────────────────────

def lock_pins(text: str) -> dict[str, str]:
    out = {}
    for line in text.splitlines():
        spec = line.split("#", 1)[0].strip()
        if "==" in spec and not spec.startswith("-"):
            name, ver = spec.split("==", 1)
            out[name.strip().lower()] = ver.strip()
    return out


def hls_version(js: str) -> str | None:
    """Same reading as tools/upgrade.py: the debug-log string every build
    carries, the `version` getter only as a fallback."""
    m = (re.search(r"hls\.js version (\d+\.\d+\.\d+[^\"'\s]*)", js)
         or re.search(r'version"?[^"]{0,40}?return\s*"(\d+\.\d+\.\d+[^"]*)"', js))
    return m.group(1) if m else None


def quote(text: str) -> str:
    """shields.io escaping: `-`/`_` are field separators and are DOUBLED."""
    return (text.replace("-", "--").replace("_", "__").replace(" ", "%20")
                .replace("·", "%C2%B7").replace(",", "%2C").replace("+", "%2B"))


def badge(label: str, message: str, color: str, link: str) -> str:
    return f"[![{label} {message}]({SHIELDS}/{quote(label)}-{quote(message)}-{color}.svg)]({link})"


def render(stack: dict) -> str:
    """The strip. `stack` maps label → version (None = not available here),
    plus an optional 'vulns' = (count, date) from osv.dev."""
    runtime = [("python", "https://www.python.org/"), ("sqlite", "https://sqlite.org/"),
               ("openssl", "https://openssl-library.org/")]
    runtime += [(label, f"https://pypi.org/project/{pkg}/") for label, _, pkg in RUNTIME_PKGS]
    runtime += [("hls.js", "https://github.com/video-dev/hls.js")]
    tooling = [("node", "#keeping-the-toolchain-current"),
               ("playwright", "https://playwright.dev/"),
               ("ruff", "https://docs.astral.sh/ruff/"), ("ffmpeg", "https://ffmpeg.org/")]

    def row(items, color):
        return " ".join(badge(label, stack[label], color, link)
                        for label, link in items if stack.get(label))

    lines = [BEGIN, f"**Runtime** {row(runtime, 'blue')}  ",
             f"**Tooling** {row(tooling, 'lightgrey')}  "]
    if stack.get("vulns"):
        count, date = stack["vulns"]
        lines.append("**Security** " + badge(
            "known vulnerabilities", f"{count} · osv.dev {date}",
            "brightgreen" if count == 0 else "red", "docs/UPGRADE.md"))
    lines.append(END)
    return "\n".join(lines)


def pinned_badges(stack: dict) -> list[str]:
    """The badges every clone must agree on — what tests/test_versions.py gates."""
    labels = [label for label, _, _ in RUNTIME_PKGS + TOOLING_PKGS] + ["hls.js"]
    every = re.findall(r"\[!\[[^\]]*\]\([^)]*\)\]\([^)]*\)", render(stack))
    return [b for b in every if any(b.startswith(f"[![{label} ") for label in labels)]


# ── collecting ───────────────────────────────────────────────────────────

def _out(argv) -> str:
    try:
        return subprocess.run(argv, capture_output=True, text=True, timeout=30,
                              check=False).stdout
    except (OSError, subprocess.TimeoutExpired):
        return ""


def pinned_stack() -> dict:
    stack = {}
    pins = {**lock_pins(DEV_LOCK.read_text()), **lock_pins(LOCK.read_text())}
    for label, _, pkg in RUNTIME_PKGS + TOOLING_PKGS:
        stack[label] = pins.get(pkg)
    stack["hls.js"] = hls_version(HLS.read_text(encoding="utf-8", errors="replace"))
    return stack


def platform_stack() -> dict:
    stack = {}
    probe = _out([str(VENV_PY), "-c",
                  "import sys,sqlite3,ssl,os,playwright;"
                  "print(sys.version.split()[0]);print(sqlite3.sqlite_version);"
                  "print(ssl.OPENSSL_VERSION.split()[1]);"
                  "print(os.path.join(os.path.dirname(playwright.__file__),'driver','node'))"])
    parts = probe.split()
    if len(parts) >= 3:
        stack.update(python=parts[0], sqlite=parts[1], openssl=parts[2])
    if len(parts) == 4:
        node = _out([parts[3], "--version"]).strip().lstrip("v")
        stack["node"] = f"{node} · tests only" if node else None
    m = re.search(r"ffmpeg version (\S+)", _out(["ffmpeg", "-version"]))
    stack["ffmpeg"] = m.group(1) if m else None
    return stack


def known_vulns() -> int:
    """osv.dev count over everything installed in the venv, plus hls.js."""
    listed = json.loads(_out([str(VENV_PY), "-m", "pip", "list", "--format=json"]) or "[]")
    queries = [{"package": {"name": p["name"], "ecosystem": "PyPI"}, "version": p["version"]}
               for p in listed]
    hls = hls_version(HLS.read_text(encoding="utf-8", errors="replace"))
    if hls:
        queries.append({"package": {"name": "hls.js", "ecosystem": "npm"}, "version": hls})
    req = urllib.request.Request("https://api.osv.dev/v1/querybatch",
                                 data=json.dumps({"queries": queries}).encode(),
                                 headers={"Content-Type": "application/json",
                                          "User-Agent": "dlna-gateway-versions/1.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        results = json.load(r).get("results", [])
    return sum(1 for res in results if (res or {}).get("vulns"))


def current_strip() -> str:
    text = README.read_text()
    start, end = text.find(BEGIN), text.find(END)
    if start == -1 or end == -1:
        raise SystemExit(f"README.md has no version markers; add {BEGIN} and {END}")
    return text[start:end + len(END)]


def written_vulns() -> tuple[int, str] | None:
    """Keep the last osv.dev result when re-rendering without the network."""
    m = re.search(r"known%20vulnerabilities-(\d+)%20%C2%B7%20osv.dev%20(\d{4}-\d{2}-\d{2})",
                  current_strip().replace("--", "-"))
    return (int(m.group(1)), m.group(2)) if m else None


def main(argv) -> int:
    stack = {**pinned_stack(), **platform_stack()}
    if "--write" in argv:
        try:
            stack["vulns"] = (known_vulns(), datetime.date.today().isoformat())
        except (OSError, ValueError) as e:
            print(f"osv.dev unreachable ({e}) — keeping the last security badge")
            stack["vulns"] = written_vulns()
        strip = render(stack)
        current = current_strip()
        README.write_text(README.read_text().replace(current, strip, 1))
        print("Version strip updated." if strip != current else "Version strip was already right.")
        return 0
    stack["vulns"] = written_vulns()
    if current_strip() == render(stack):
        print("Version strip is current.")
        return 0
    print("Version strip is STALE — run: .venv/bin/python tools/versions.py --write")
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
